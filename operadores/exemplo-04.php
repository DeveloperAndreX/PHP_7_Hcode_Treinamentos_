<?php
// Operadores Logicos de Comparação exemplos praticos:

$a = 55.0;

$b = 55;

var_dump($a > $b); //false

echo "<br>";

var_dump($a < $b); // true]

echo "<br>";

var_dump($a == $b);  // operador de comparação de valor ( == )

echo "<br>";

var_dump($a === $b); // Operador de comparação de valor e Tipo;

echo "<br>";

var_dump($a =! $b); // diferente 

echo "<br>";

var_dump($a ==! $b); // diferente o tipo de dado e o valor;







?>